    /** Selling as the shop sees it. */
    private final class Link implements SellLink {

        @Override
        public long sellBack(Player player, String itemKey) {
            return SellFeature.this.worth.unitPriceFor(player, itemKey);
        }

        @Override
        public long carried(Player player, String itemKey) {
            return SellFeature.this.sales.builder().carried(player, SellFeature.this.settings.get()).getOrDefault(itemKey, 0L);
        }

        @Override
        public boolean offerSell(Player player, String itemKey, Runnable back) {
            return SellFeature.this.sales.sellType(player, itemKey, true, back) == SellService.Outcome.ASKED;
        }
    }

