    /** Every base price is in the table unchanged and every price is a whole amount within the money limit. */
    private String checkTable() {
        SellSettings s = this.settings.get();
        WorthTable table = s.table();
        if (!s.tableProblems().isEmpty()) {
            return String.join("; ", s.tableProblems());
        }
        if (table.size() == 0) {
            return "the worth table is empty";
        }
        for (Map.Entry<String, Long> base : table.base().entrySet()) {
            String item = base.getKey();
            if (table.unsellable().contains(item)) {
                continue;
            }
            WorthTable.Entry entry = table.entry(item);
            if (entry == null) {
                return item + " has a base price but is missing from the table";
            }
            if (entry.origin() == WorthTable.Origin.BASE && entry.price() != base.getValue()) {
                return item + " has base price " + base.getValue() + " but the table says " + entry.price();
            }
        }
        long max = this.services.core().get().money().maxAmount();
        for (Map.Entry<String, WorthTable.Entry> entry : table.entries().entrySet()) {
            long price = entry.getValue().price();
            if (price < 1 || price > max) {
                return entry.getKey() + " has the price " + price + ", outside 1.." + max;
            }
            if (entry.getValue().origin() == WorthTable.Origin.DERIVED && entry.getValue().recipe() == null) {
                return entry.getKey() + " is derived but names no recipe";
            }
        }
        return null;
    }

    /**
     * The shop is checked against the best multiplier anyone can reach (the best rank plus the top mastery bonus),
     * and no item the shop sells can be sold back for as much as it costs, even at that multiplier.
     */
    private String checkShopWithMastery() {
        SellSettings s = this.settings.get();
        BigDecimal highest = BigDecimal.valueOf(s.highestRankMultiplier()).add(s.mastery().maxBonus());
        if (BigDecimal.valueOf(s.highestMultiplier()).compareTo(highest) != 0) {
            return "the highest multiplier " + s.highestMultiplier() + " is not rank plus the top mastery bonus " + highest;
        }
        if (Math.abs(this.worth.current().highestMultiplier() - s.highestMultiplier()) > 1e-9) {
            return "the shop validates against " + this.worth.current().highestMultiplier() + " instead of " + s.highestMultiplier();
        }
        ShopOffers offers = this.shop.get();
        for (Map.Entry<String, WorthTable.Entry> entry : s.table().prices().entrySet()) {
            OptionalLong price = offers.price(entry.getKey());
            if (price.isEmpty()) {
                continue;
            }
            long best = SaleMath.withMultiplier(entry.getValue().price(), highest);
            if (best >= price.getAsLong()) {
                return entry.getKey() + " costs $" + price.getAsLong() + " in the shop but sells back for $" + best
                    + " at " + Multipliers.format(highest.doubleValue()) + "x";
            }
        }
        return null;
    }

    /** Every sellable item is in a category that exists; listed items are in the category that lists them. */
    private String checkCategories() {
        SellSettings s = this.settings.get();
        SellCategories categories = s.categories();
        for (Map.Entry<String, WorthTable.Entry> entry : s.table().entries().entrySet()) {
            String category = entry.getValue().category();
            if (categories.category(category) == null) {
                return entry.getKey() + " is in the category " + category + ", which does not exist";
            }
            String listed = categories.listed(entry.getKey());
            if (listed != null && !listed.equals(category)) {
                return entry.getKey() + " is listed in " + listed + " but the table puts it in " + category;
            }
        }
        String iron = s.table().category("minecraft:iron_block");
        if (iron != null && categories.category("mining") != null && !"mining".equals(iron)) {
            return "iron blocks should inherit mining from iron ingots, got " + iron;
        }
        return null;
    }

    /** Taking one kind out of a box leaves every other stack where it was, and an emptied box is plain again. */
    private String checkShulkerRebuild() {
        ItemStack box = ItemStack.of(Material.SHULKER_BOX);
        List<ItemStack> contents = new ArrayList<>();
        for (int i = 0; i < 27; i++) {
            contents.add(ItemStack.empty());
        }
        contents.set(3, ItemStack.of(Material.DIAMOND, 10));
        contents.set(7, ItemStack.of(Material.STICK, 5));
        contents.set(20, ItemStack.of(Material.DIAMOND, 64));
        ItemStack filled = ContainerItems.rebuild(box, contents);
        List<ItemStack> read = ContainerItems.contents(filled);
        if (read.size() < 21 || read.get(7).getType() != Material.STICK || read.get(20).getAmount() != 64) {
            return "a filled box does not keep positions: " + read;
        }
        ContainerItems.Extraction<ItemStack> taken = ContainerItems.extract(read, stack -> stack.getType() == Material.DIAMOND, 70);
        if (taken.units() != 70) {
            return "70 diamonds should come out, got " + taken.units();
        }
        List<ItemStack> after = ContainerItems.contents(ContainerItems.rebuild(filled, taken.remaining()));
        if (after.size() < 21 || after.get(7).getType() != Material.STICK || after.get(7).getAmount() != 5
            || after.get(20).getType() != Material.DIAMOND || after.get(20).getAmount() != 4 || !after.get(3).isEmpty()) {
            return "the rebuilt box moved or lost other stacks: " + after;
        }
        ContainerItems.Extraction<ItemStack> rest = ContainerItems.extract(after, stack -> true, Long.MAX_VALUE);
        ItemStack emptied = ContainerItems.rebuild(filled, rest.remaining());
        if (!emptied.isSimilar(box)) {
            return "an emptied plain box is not a plain box again";
        }
        if (ContainerItems.isShulker(box.asQuantity(2))) {
            return "a stacked box would be opened";
        }
        return null;
    }

    /** A marked item does not sell; marking keeps the item otherwise unchanged. */
    private String checkTradeMarker() {
        ItemStack emerald = ItemStack.of(Material.EMERALD, 3);
        ItemStack marked = TradeGuard.mark(emerald);
        if (!TradeGuard.marked(marked) || TradeGuard.marked(emerald)) {
            return "the trade marker is not applied to a copy";
        }
        if (this.worth.table().price("minecraft:emerald") > 0 && this.worth.unitPrice(marked) != 0) {
            return "a marked emerald sells";
        }
        if (marked.getType() != Material.EMERALD || marked.getAmount() != 3) {
            return "marking changed the item";
        }
        return null;
    }

    /** A plain stack sells; renamed, custom-data and damaged copies of it don't. */
    private String checkPlainItems() {
        Material plain = null;
        Material damageable = null;
        for (String key : this.worth.table().entries().keySet()) {
            Material material = Material.matchMaterial(key);
            if (material == null || !material.isItem()) {
                continue;
            }
            if (plain == null && material.getMaxStackSize() > 1) {
                plain = material;
            }
            if (damageable == null && material.getMaxDurability() > 0) {
                damageable = material;
            }
        }
        if (plain == null) {
            return "no stackable item is sellable";
        }
        ItemStack stack = ItemStack.of(plain, 3);
        if (this.worth.unitPrice(stack) <= 0) {
            return "a plain " + plain.getKey() + " does not sell";
        }
        ItemStack renamed = stack.clone();
        renamed.setData(DataComponentTypes.CUSTOM_NAME, Component.text("Renamed"));
        if (this.worth.unitPrice(renamed) != 0) {
            return "a renamed " + plain.getKey() + " sells";
        }
        ItemStack tagged = stack.clone();
        tagged.editPersistentDataContainer(pdc -> pdc.set(new NamespacedKey(this.services.plugin(), "selftest"),
            PersistentDataType.BYTE, (byte) 1));
        if (this.worth.unitPrice(tagged) != 0) {
            return "a " + plain.getKey() + " with custom data sells";
        }
        if (damageable != null) {
            ItemStack damaged = ItemStack.of(damageable);
            damaged.setData(DataComponentTypes.DAMAGE, 1);
            if (this.worth.unitPrice(damaged) != 0) {
                return "a damaged " + damageable.getKey() + " sells";
            }
        }
        return null;
    }
