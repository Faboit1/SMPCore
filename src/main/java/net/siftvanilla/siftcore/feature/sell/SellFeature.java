    /**
     * @param combat what keeps combat-tagged players from selling
     * @param orders the buy-order market, read whenever a sale is worked out ({@link OrderMarket#NONE} without
     *               the orders feature)
     */
    public SellFeature(Services services, List<ConfigProblem> problems, CombatStatus combat, Supplier<OrderMarket> orders) {
        this.services = services;
        this.logger = services.plugin().getLogger();
        ServerItems.Snapshot snapshot = ServerItems.snapshot();
        ItemCatalog catalog = snapshot.catalog();
        this.recipesSeen = snapshot.recipes();
        this.recipesSkipped = snapshot.skippedRecipes();
        AtomicReference<SellSettings> latest = new AtomicReference<>();
        this.settings = services.configs().register("features/sell.yml", reader -> {
            SellSettings parsed = SellSettings.parse(reader, catalog, services.core().get().money());
            latest.set(parsed);
            return parsed;
        }, problems);
        this.mastery = new MasteryBook(services.database(), this.logger);
        this.worth = new WorthService(this.settings, latest, services.scheduler()::owns, this.mastery);
        services.lang().register(SellMessages.class);
        Permissions perms = services.permissions();
        perms.declare(SellCommands.SELL, "Open the sell menu with /sell, and /sell mastery, /sell top and /sell history", true);
        perms.declare(SellCommands.SELL_HAND, "Sell the item in your hand with /sell hand, and all of its kind with /sell hand all", true);
        perms.declare(SellCommands.SELL_ALL, "Sell your whole inventory with /sell all", true);
        perms.declare(SellCommands.WORTH, "See what items sell for with /worth and the price list", true);
        perms.declare(SellCommands.WORTH_DETAILS, "See where a /worth price comes from", false);
        perms.declare(SellCommands.ADMIN, "Look at and change players' sell mastery with /sell admin", false);
        for (Map.Entry<String, Double> tier : this.settings.get().multipliers().entrySet()) {
            perms.declare(Multipliers.node(tier.getKey()), "Sell for " + Multipliers.format(tier.getValue())
                + " times the worth (the highest granted tier wins)", PermissionDefault.FALSE);
        }
        services.settings().register(SellService.CONFIRM);
        // Sale receipts are a shared setting (spawner storage sales follow it too); selling acts on it.
        services.settings().reads(SharedSettings.SELL_RECEIPTS);
        ItemHandout handout = new ItemHandout(services.deliveries(), this.logger);
        this.bids = new OrderBids(orders);
        // "Sell to buy orders first" is offered only while there are buy orders (the orders feature may be off, and it
        // starts after this one): registered now, so the server's overrides can always name it.
        services.settings().register(SettingCategories.GENERAL, SellService.ORDERS, SettingOptions.<Boolean>builder()
            .availableWhen(() -> this.bids.market().available()).build());
        SaleBuilder builder = new SaleBuilder(this.worth, this.bids);
        this.sales = new SellService(services, this.worth, this.settings, handout, builder, this.bids, this.mastery, combat);
        this.menus = new SellMenus(services, this.worth, this.settings, this.sales, handout);
        this.top = new TopSellers(services.database(), services.directory()::name);
        this.history = new SellHistory(services);
        this.dialogs = new SellDialogs(services, this.worth, this.settings, this.sales, this.bids, this.mastery, this.top,
            this.shop::get);
        this.dialogs.browser(this::openBrowser);
        this.sales.chooseItems(this.menus::openFilled);
        this.menus.onMastery(this.dialogs::mastery);
        this.trades = new TradeGuard(() -> this.settings.get().markTrades(), services.scheduler()::owns);
        this.commands = new SellCommands(services, this.worth, this.settings, this.sales, this.menus, this.dialogs,
            this.history, this.mastery, this.bids, this.shop::get, this::openBrowser);
        this.link = new Link();
    }

