    private void openBrowser(Player player, String category, String query) {
        openBrowser(player, category, query, null);
    }

    private void openBrowser(Player player, String category, String query, Runnable back) {
        WorthBrowser.open(this.services, player, this.worth, this.settings, this.sales, this.bids, this.shop::get,
            this.dialogs, category, query, back);
    }

    @Override
    public void enable() {
        Bukkit.getPluginManager().registerEvents(this, this.services.plugin());
        Bukkit.getPluginManager().registerEvents(this.menus, this.services.plugin());
        Bukkit.getPluginManager().registerEvents(this.trades, this.services.plugin());
        this.services.hub().register(new HubEntry("sell", 25, SellMessages.HUB_LABEL, SellMessages.HUB_DESCRIPTION,
            SellCommands.SELL, this.menus::open));
        this.services.hub().register(new HubEntry("prices", 26, SellMessages.HUB_PRICES_LABEL,
            SellMessages.HUB_PRICES_DESCRIPTION, SellCommands.WORTH, player -> openBrowser(player, null, null)));
        placeholders();
        published(this.settings.get());
        this.settings.onReload(this::published);
        for (Player online : Bukkit.getOnlinePlayers()) {
            this.mastery.load(online.getUniqueId());
            this.services.scheduler().entity(online, () -> track(online), null);
        }
        this.services.scheduler().asyncTimer(this::refreshTop, Duration.ZERO, TOP_CHECK);
    }

    /** Reads the top sellers again once the configured interval has passed since the last read. */
    private void refreshTop() {
        long age = System.currentTimeMillis() - this.top.snapshot().at();
        if (age < this.settings.get().topRefresh().toMillis() && this.top.snapshot().at() > 0) {
            return;
        }
        this.top.refresh().whenComplete((snapshot, error) -> {
            if (error != null) {
                this.logger.log(Level.WARNING, "Could not read the top sellers", error);
            }
        });
    }

    private void placeholders() {
        Placeholders placeholders = this.services.placeholders();
        placeholders.register("sell_multiplier", "Your sell multiplier from sell.yml multipliers (1 when none apply; mastery not included)",
            player -> Multipliers.format(this.worth.cachedMultiplier(player.getUniqueId())));
        placeholders.registerPrefix("sell_multiplier_", "sell_multiplier_<category>",
            "Your multiplier for a sell category, rank plus mastery, like 1.6", (player, category) -> {
                if (this.worth.categories().category(category) == null) {
                    return "";
                }
                return Multipliers.format(this.worth.cachedRates(player.getUniqueId()).multiplier(category).doubleValue());
            });
        placeholders.registerPrefix("sell_mastery_", "sell_mastery_<category>", "Your sell mastery level in a category (0-5)",
            (player, category) -> {
                if (this.worth.categories().category(category) == null) {
                    return "";
                }
                return Integer.toString(this.worth.cachedRates(player.getUniqueId()).level(category));
            });
        placeholders.register("sell_sold", "Everything you sold to the server, at base value (what mastery counts)",
            player -> this.services.money().get().format(sold(player.getUniqueId())));
        placeholders.registerPrefix("worth_", "worth_<item>", "What one plain item sells for, like worth_diamond (empty when it can't be sold)",
            (player, item) -> {
                String key = ItemKeys.normalize(item);
                long price = key == null ? 0 : this.worth.table().price(key);
                return price <= 0 ? "" : this.services.money().get().format(price);
            });
        placeholders.registerPrefix("sell_top_name_", "sell_top_name_<n>", "Name of the n-th best seller (1-10)",
            (player, place) -> topPlace(place).map(TopSellers.Entry::name).orElse(""));
        placeholders.registerPrefix("sell_top_value_", "sell_top_value_<n>", "What the n-th best seller sold, formatted (1-10)",
            (player, place) -> topPlace(place).map(entry -> this.services.money().get().format(entry.sold())).orElse(""));
    }

    private Optional<TopSellers.Entry> topPlace(String place) {
        try {
            return this.top.snapshot().place(Integer.parseInt(place));
        } catch (NumberFormatException e) {
            return Optional.empty();
        }
    }

    /** What a player sold in total: live for online players, the last top-sellers read otherwise. */
    private long sold(UUID player) {
        return Math.max(this.mastery.total(player), this.top.snapshot().byUuid().getOrDefault(player, 0L));
    }

    /** Logs the table and writes the generated file (at startup and after every successful reload). */
    private void published(SellSettings settings) {
        WorthTable table = settings.table();
        this.logger.info("Worth table: " + table.size() + " sellable items (" + table.count(WorthTable.Origin.BASE) + " base, "
            + table.count(WorthTable.Origin.DERIVED) + " from recipes, " + table.count(WorthTable.Origin.OVERRIDE)
            + " overrides) in " + settings.categories().ids().size() + " categories, using " + settings.recipes().size()
            + " of " + this.recipesSeen + " recipes (" + this.recipesSkipped + " special recipes skipped). Best multiplier "
            + Multipliers.format(settings.highestMultiplier()) + "x (rank " + Multipliers.format(settings.highestRankMultiplier())
            + "x plus mastery " + Multipliers.format(settings.mastery().maxBonus().doubleValue()) + ").");
        String text = WorthFile.render(settings, Instant.now());
        Path file = this.services.plugin().getDataFolder().toPath().resolve(WorthFile.NAME);
        this.services.scheduler().async(() -> {
            try {
                WorthFile.write(file, text);
            } catch (IOException e) {
                this.logger.log(Level.WARNING, "Could not write " + WorthFile.NAME, e);
            }
        });
    }

    /**
     * Reads the player's mastery totals before they enter the world (the auth thread may wait), so their first sale
     * already counts from the right level.
     */
    @EventHandler(priority = EventPriority.MONITOR)
    public void onPreLogin(AsyncPlayerPreLoginEvent event) {
        if (event.getLoginResult() != AsyncPlayerPreLoginEvent.Result.ALLOWED) {
            return;
        }
        try {
            this.mastery.load(event.getUniqueId()).get(LOGIN_LOAD_SECONDS, TimeUnit.SECONDS);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        } catch (ExecutionException | TimeoutException e) {
            this.logger.log(Level.WARNING, "Reading the sell mastery of " + event.getName() + " at login took too long;"
                + " it finishes in the background", e);
        }
    }

    @EventHandler(priority = EventPriority.MONITOR)
    public void onJoin(PlayerJoinEvent event) {
        if (!this.mastery.present(event.getPlayer().getUniqueId())) {
            // Not read at login (it timed out, or a duplicate login's quit forgot it): read it now.
            this.mastery.load(event.getPlayer().getUniqueId());
        }
        track(event.getPlayer());
    }

    @EventHandler(priority = EventPriority.MONITOR)
    public void onQuit(PlayerQuitEvent event) {
        this.worth.forget(event.getPlayer().getUniqueId());
        this.mastery.forget(event.getPlayer().getUniqueId());
    }

    /** Reads the player's multiplier now and every minute while they are online (on their thread). */
    private void track(Player player) {
        this.worth.refresh(player);
        this.services.scheduler().entityTimer(player, () -> this.worth.refresh(player), null,
            MULTIPLIER_REFRESH_TICKS, MULTIPLIER_REFRESH_TICKS);
    }

